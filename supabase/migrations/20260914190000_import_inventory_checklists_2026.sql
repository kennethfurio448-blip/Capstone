begin;

create or replace function public.medtrack_normalize_inventory_text(p_value text)
returns text
language sql
immutable
strict
set search_path = ''
as $$
    select regexp_replace(lower(trim(p_value)), '[^a-z0-9]+', '', 'g');
$$;

revoke all on function public.medtrack_normalize_inventory_text(text) from public;

create table if not exists public.inventory_import_batches (
    id uuid primary key,
    source_file text not null,
    source_kind text not null,
    status text not null default 'staged',
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    completed_at timestamptz,
    constraint inventory_import_batches_source_file_check
        check (trim(source_file) <> ''),
    constraint inventory_import_batches_source_kind_check
        check (source_kind in ('xlsx', 'doc', 'docx', 'csv')),
    constraint inventory_import_batches_status_check
        check (status in ('staged', 'imported', 'completed_with_pending', 'failed')),
    constraint inventory_import_batches_metadata_check
        check (jsonb_typeof(metadata) = 'object')
);

create table if not exists public.inventory_import_rows (
    id bigint generated by default as identity primary key,
    batch_id uuid not null references public.inventory_import_batches(id),
    source_locator text not null,
    target_module text not null,
    raw_record jsonb not null,
    normalized_record jsonb not null,
    validation_status text not null default 'pending',
    issues jsonb not null default '[]'::jsonb,
    target_table text,
    target_id text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint inventory_import_rows_locator_unique
        unique (batch_id, source_locator),
    constraint inventory_import_rows_locator_check
        check (trim(source_locator) <> ''),
    constraint inventory_import_rows_module_check
        check (target_module in ('medical_supplies', 'medical_equipment', 'mobility')),
    constraint inventory_import_rows_status_check
        check (validation_status in ('ready', 'pending', 'duplicate', 'imported', 'error')),
    constraint inventory_import_rows_raw_check
        check (jsonb_typeof(raw_record) = 'object'),
    constraint inventory_import_rows_normalized_check
        check (jsonb_typeof(normalized_record) = 'object'),
    constraint inventory_import_rows_issues_check
        check (jsonb_typeof(issues) = 'array')
);

create index if not exists inventory_import_rows_batch_status_idx
    on public.inventory_import_rows (batch_id, validation_status);

create index if not exists medical_supplies_normalized_name_idx
    on public.medical_supplies (public.medtrack_normalize_inventory_text(name));

create index if not exists medical_equipment_normalized_name_idx
    on public.medical_equipment (public.medtrack_normalize_inventory_text(name));

create index if not exists mobility_assets_normalized_name_idx
    on public.mobility_assets (public.medtrack_normalize_inventory_text(name));

alter table public.inventory_import_batches enable row level security;
alter table public.inventory_import_rows enable row level security;

revoke all on table public.inventory_import_batches from anon, authenticated;
revoke all on table public.inventory_import_rows from anon, authenticated;
grant select on table public.inventory_import_batches to authenticated;
grant select on table public.inventory_import_rows to authenticated;
grant select, insert, update on table public.inventory_import_batches to service_role;
grant select, insert, update on table public.inventory_import_rows to service_role;
grant usage, select on sequence public.inventory_import_rows_id_seq to service_role;

drop policy if exists "Admins can read inventory import batches"
on public.inventory_import_batches;
create policy "Admins can read inventory import batches"
on public.inventory_import_batches for select to authenticated
using (public.medtrack_is_admin());

drop policy if exists "Admins can read inventory import rows"
on public.inventory_import_rows;
create policy "Admins can read inventory import rows"
on public.inventory_import_rows for select to authenticated
using (public.medtrack_is_admin());

